import { buildTeamJsonSchema } from "#/config/json-schema.js";
import { documentedCodes } from "#/config/documented-codes.js";
import { WARNING_CODES } from "#/config/warning-codes.js";
import { asSchema, walk } from "./schema-walk.js";
import type { Schema } from "./types.js";

const GENERATED = (script: string) => `<!-- Generated by \`${script}\`. Do not edit by hand. -->`;

/** Puts each top-level key's schema description above it in the example file. */
function annotate(example: string, root: Schema): string {
  const props = asSchema(root["properties"]) ?? {};
  return example
    .split("\n")
    .flatMap((line) => {
      const key = /^([a-z_]+):/.exec(line)?.[1];
      const description = key ? asSchema(props[key])?.["description"] : undefined;
      return typeof description === "string" ? ["", `# ${description}`, line] : [line];
    })
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

export const TEAM_REFERENCE_COMMAND = "pnpm --filter @outstaff/core run docs:schema";

/** Markdown for the team.yaml reference page, generated from the zod schema. */
export function renderTeamYamlReference(example: string): string {
  const root = buildTeamJsonSchema();
  const out: string[] = [
    "---",
    "title: team.yaml reference",
    "description: Every field of the team config, with its type, default and allowed values.",
    "---",
    "",
    GENERATED(TEAM_REFERENCE_COMMAND),
    "",
    "The team config lives at `.outstaff/team.yaml` in your repository. For a prose tour of the sections, see [Team config](/concepts/team-config/). Problems found by `ost validate` are listed in [Validation codes](/reference/validation-codes/). The same schema is published as JSON Schema in `packages/core/schema/team.schema.json`.",
    "",
    "Paths use `[]` for list items and `<key>` for a map entry whose key you choose.",
    "",
    "Only the office loads this file. Each agent receives it from the office when it connects, whole, so it holds no secrets: fields such as `people[].network.http[].token` name a secret, and each container reads the value from its own secrets.",
    "",
    "## Example",
    "",
    'A complete file for the synthetic team "acme".',
    "",
    "```yaml",
    annotate(example, root),
    "```",
  ];

  const required = new Set(Array.isArray(root["required"]) ? (root["required"] as string[]) : []);
  const fields: string[] = [];
  for (const [key, value] of Object.entries(asSchema(root["properties"]) ?? {})) {
    const node = asSchema(value);
    if (node) {
      walk(key, node, required.has(key), root, fields);
    }
  }

  return `${[...out, "", "## Fields", "", fields.join("\n\n")].join("\n")}\n`;
}

/** Markdown for the validation codes page, generated from `documentedCodes`. */
export function renderValidationCodes(): string {
  const warnings = new Set<string>(Object.values(WARNING_CODES));
  const rows = (isWarning: boolean) =>
    Object.entries(documentedCodes)
      .filter(([c]) => warnings.has(c) === isWarning)
      .toSorted(([a], [b]) => a.localeCompare(b))
      .map(([c, text]) => `| \`${c}\` | ${text} |`);

  return `${[
    "---",
    "title: Validation codes",
    "description: The error and warning codes reported by ost validate.",
    "---",
    "",
    GENERATED("pnpm --filter @outstaff/core run docs:schema"),
    "",
    "`ost validate` and the loader report every problem with a stable code, so scripts and assistants can match on it. Codes never change meaning; new ones are added. See the [CLI reference](/reference/cli/) for exit codes and the [team.yaml reference](/reference/team-yaml/) for the fields.",
    "",
    "## Errors",
    "",
    "An error means the config cannot be used. `ost validate` exits with 1.",
    "",
    "| Code | Meaning |",
    "| --- | --- |",
    ...rows(false),
    "",
    "## Warnings",
    "",
    "A warning describes something that will not work as written or a default that applies. `ost validate` still exits with 0.",
    "",
    "| Code | Meaning |",
    "| --- | --- |",
    ...rows(true),
  ].join("\n")}\n`;
}
