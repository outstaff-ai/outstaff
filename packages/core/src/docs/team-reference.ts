import { buildTeamJsonSchema } from "../config/json-schema.js";
import { documentedCodes, WARNING_CODES } from "../config/validate.js";

type Schema = Record<string, unknown>;

const GENERATED = (script: string) => `<!-- Generated by \`${script}\`. Do not edit by hand. -->`;

const asSchema = (value: unknown): Schema | undefined =>
  value && typeof value === "object" && !Array.isArray(value) ? (value as Schema) : undefined;

const asList = (value: unknown): Schema[] =>
  Array.isArray(value) ? value.map((v) => asSchema(v)).filter((v) => v !== undefined) : [];

const code = (value: unknown) => `\`${typeof value === "string" ? value : JSON.stringify(value)}\``;

/** Inlines $ref and single-entry allOf; returns undefined for a ref already being expanded. */
function resolve(node: Schema, root: Schema, stack: string[]): Schema | undefined {
  let current = node;
  const ref = current["$ref"];
  if (typeof ref === "string") {
    if (stack.includes(ref)) {
      return undefined;
    }

    const name = ref.replace("#/definitions/", "");
    const target = asSchema(asSchema(root["definitions"])?.[name]);
    if (!target) {
      return current;
    }

    stack.push(ref);
    const { $ref: _ref, ...rest } = current;
    return { ...target, ...rest };
  }

  const all = asList(current["allOf"]);
  if (all.length === 1 && all[0]) {
    const { allOf: _allOf, ...rest } = current;
    const inner = resolve(all[0], root, stack);
    current = inner ? { ...inner, ...rest } : rest;
  }

  return current;
}

function typeOf(node: Schema, root: Schema, stack: string[]): string {
  const resolved = resolve(node, root, [...stack]);
  if (!resolved) {
    return "condition";
  }

  const variants = asList(resolved["anyOf"]);
  if (variants.length > 0) {
    const parts = variants.map((v) => typeOf(v, root, stack));
    return [...new Set(parts)].join(" or ");
  }

  if ("const" in resolved) {
    return typeof resolved["const"];
  }

  const type = resolved["type"];
  if (type === "array") {
    const items = asSchema(resolved["items"]);
    return `list of ${items ? typeOf(items, root, stack) : "values"}`;
  }

  if (type === "object") {
    return resolved["properties"] ? "object" : "map";
  }

  return typeof type === "string" ? type : "any";
}

function constraints(node: Schema): string[] {
  const out: string[] = [];
  const bound = (key: string, label: string) => {
    const value = node[key];
    if (typeof value === "number" && value !== Number.MAX_SAFE_INTEGER) {
      out.push(`${label} ${value}`);
    }
  };

  bound("minimum", "Minimum");
  bound("maximum", "Maximum");
  bound("minLength", "Minimum length");
  bound("maxLength", "Maximum length");
  bound("minItems", "Minimum items");
  if (typeof node["pattern"] === "string") {
    out.push(`Must match ${code(node["pattern"])}`);
  }

  return out;
}

function enumValues(node: Schema): unknown[] | undefined {
  if (Array.isArray(node["enum"])) {
    return node["enum"];
  }

  const items = asSchema(node["items"]);
  if (items && Array.isArray(items["enum"])) {
    return items["enum"];
  }

  const found = asList(node["anyOf"]).flatMap((v) => enumValues(v) ?? []);
  return found.length > 0 ? [...new Set(found)] : undefined;
}

type Child = { segment: string; node: Schema; required: boolean };

function children(node: Schema, root: Schema, stack: string[]): Child[] {
  const out: Child[] = [];
  const collect = (candidate: Schema) => {
    const resolved = resolve(candidate, root, [...stack]);
    if (!resolved) {
      return;
    }

    const required = new Set(
      Array.isArray(resolved["required"]) ? (resolved["required"] as string[]) : [],
    );

    const props = asSchema(resolved["properties"]);
    for (const [key, value] of Object.entries(props ?? {})) {
      const child = asSchema(value);
      if (child) {
        out.push({ segment: `.${key}`, node: child, required: required.has(key) });
      }
    }

    const extra = asSchema(resolved["additionalProperties"]);
    if (extra && asSchema(extra["properties"])) {
      out.push({ segment: ".<key>", node: extra, required: false });
    }

    const items = asSchema(resolved["items"]);
    if (items) {
      out.push({ segment: "[]", node: items, required: false });
    }

    for (const variant of asList(resolved["anyOf"])) {
      collect(variant);
    }
  };

  collect(node);
  return out;
}

/** Rule ids and event names repeat across a variant; keep the first section per path. */
function section(path: string, node: Schema, required: boolean, root: Schema, stack: string[]) {
  const resolved = resolve(node, root, [...stack]) ?? node;
  const depth = path.split(/[.[]/).filter((p) => p !== "]").length;
  const lines = [`${"#".repeat(Math.min(depth + 1, 4))} ${path}`, ""];
  const description = typeof resolved["description"] === "string" ? resolved["description"] : "";
  if (description) {
    lines.push(description, "");
  }

  lines.push(`- Type: ${code(typeOf(resolved, root, stack))}`);
  lines.push(`- ${required ? "Required" : "Optional"}`);
  if ("default" in resolved) {
    lines.push(`- Default: ${code(resolved["default"])}`);
  }

  if ("const" in resolved) {
    lines.push(`- Must be ${code(resolved["const"])}`);
  }

  const values = enumValues(resolved);
  if (values) {
    lines.push(`- Allowed values: ${values.map((v) => code(v)).join(", ")}`);
  }

  const names = asSchema(resolved["propertyNames"]);
  if (names && Array.isArray(names["enum"])) {
    lines.push(`- Allowed keys: ${names["enum"].map((v) => code(v)).join(", ")}`);
  }

  for (const rule of constraints(resolved)) {
    lines.push(`- ${rule}`);
  }

  return lines.join("\n");
}

function walk(path: string, node: Schema, required: boolean, root: Schema, out: string[]) {
  walkWith(path, node, required, root, out, [], new Set());
}

function walkWith(
  path: string,
  node: Schema,
  required: boolean,
  root: Schema,
  out: string[],
  stack: string[],
  seen: Set<string>,
) {
  if (seen.has(path)) {
    return;
  }

  seen.add(path);
  const next = [...stack];
  const resolved = resolve(node, root, next);
  out.push(section(path, node, required, root, stack));
  if (!resolved) {
    return;
  }

  for (const child of children(resolved, root, next)) {
    walkWith(`${path}${child.segment}`, child.node, child.required, root, out, next, seen);
  }
}

/** Puts each top-level key's schema description above it in the example file. */
function annotate(example: string, root: Schema): string {
  const props = asSchema(root["properties"]) ?? {};
  return example
    .split("\n")
    .flatMap((line) => {
      const key = /^([a-z_]+):/.exec(line)?.[1];
      const description = key ? asSchema(props[key])?.["description"] : undefined;
      return typeof description === "string" ? ["", `# ${description}`, line] : [line];
    })
    .join("\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

export const TEAM_REFERENCE_COMMAND = "pnpm --filter @outstaff/core run docs:schema";

/** Markdown for the team.yaml reference page, generated from the zod schema. */
export function renderTeamYamlReference(example: string): string {
  const root = buildTeamJsonSchema();
  const out: string[] = [
    "---",
    "title: team.yaml reference",
    "description: Every field of the team config, with its type, default and allowed values.",
    "---",
    "",
    GENERATED(TEAM_REFERENCE_COMMAND),
    "",
    "The team config lives at `.outstaff/team.yaml` in your repository. For a prose tour of the sections, see [Team config](/concepts/team-config/). Problems found by `ost validate` are listed in [Validation codes](/reference/validation-codes/). The same schema is published as JSON Schema in `packages/core/schema/team.schema.json`.",
    "",
    "Paths use `[]` for list items and `<key>` for a map entry whose key you choose.",
    "",
    "## Example",
    "",
    'A complete file for the synthetic team "acme".',
    "",
    "```yaml",
    annotate(example, root),
    "```",
  ];

  const required = new Set(Array.isArray(root["required"]) ? (root["required"] as string[]) : []);
  const fields: string[] = [];
  for (const [key, value] of Object.entries(asSchema(root["properties"]) ?? {})) {
    const node = asSchema(value);
    if (node) {
      walk(key, node, required.has(key), root, fields);
    }
  }

  return `${[...out, "", "## Fields", "", fields.join("\n\n")].join("\n")}\n`;
}

/** Markdown for the validation codes page, generated from `documentedCodes`. */
export function renderValidationCodes(): string {
  const warnings = new Set<string>(Object.values(WARNING_CODES));
  const rows = (isWarning: boolean) =>
    Object.entries(documentedCodes)
      .filter(([c]) => warnings.has(c) === isWarning)
      .toSorted(([a], [b]) => a.localeCompare(b))
      .map(([c, text]) => `| \`${c}\` | ${text} |`);

  return `${[
    "---",
    "title: Validation codes",
    "description: The error and warning codes reported by ost validate.",
    "---",
    "",
    GENERATED("pnpm --filter @outstaff/core run docs:schema"),
    "",
    "`ost validate` and the loader report every problem with a stable code, so scripts and assistants can match on it. Codes never change meaning; new ones are added. See the [CLI reference](/reference/cli/) for exit codes and the [team.yaml reference](/reference/team-yaml/) for the fields.",
    "",
    "## Errors",
    "",
    "An error means the config cannot be used. `ost validate` exits with 1.",
    "",
    "| Code | Meaning |",
    "| --- | --- |",
    ...rows(false),
    "",
    "## Warnings",
    "",
    "A warning describes something that will not work as written or a default that applies. `ost validate` still exits with 0.",
    "",
    "| Code | Meaning |",
    "| --- | --- |",
    ...rows(true),
  ].join("\n")}\n`;
}
