import { fieldRows, payloadSchema, table } from "../docs-format.js";
import { LINK_MESSAGE_META, LINK_METHOD_META } from "./meta.js";
import {
  LINK_VERSION,
  LINK_ERROR_CODES,
  linkMessageSchema,
  requestSchema,
  RESULT_SCHEMAS,
} from "./schemas.js";
import type { LinkMessageType, LinkMethod } from "./types.js";

const FROM = { office: "the office", service: "the service", both: "either side" };
const HEADER = ["Field", "Type", "Required", "Description"];

const fields = (schema: Parameters<typeof payloadSchema>[0]) => {
  const rows = fieldRows(payloadSchema(schema), "");
  return rows.length ? table([HEADER, ...rows]) : ["No fields."];
};

function messageSection(type: LinkMessageType): string[] {
  const meta = LINK_MESSAGE_META[type];
  const option = linkMessageSchema.options.find((o) => o.shape.type.value === type)!;
  return [
    `### \`${type}\``,
    "",
    meta.summary,
    "",
    `Sent by: ${FROM[meta.from]}.`,
    "",
    ...(type === "request" || type === "response"
      ? ["The fields depend on the method; see Methods."]
      : fields(option.shape.payload)),
    "",
  ];
}

function methodSection(method: LinkMethod): string[] {
  const option = requestSchema.options.find((o) => o.shape.method.value === method)!;
  return [
    `### \`${method}\``,
    "",
    LINK_METHOD_META[method],
    "",
    "Params:",
    "",
    ...fields(option.shape.params),
    "",
    "Result:",
    "",
    ...fields(RESULT_SCHEMAS[method]),
    "",
  ];
}

/** The reference page for the office link; the docs build commits the output of this function. */
export function renderLinkReference(): string {
  const lines = [
    "---",
    "title: Office link",
    "description: The messages an office and a monitoring or management service exchange over the connection the office opens to it.",
    "---",
    "",
    "<!-- Generated by `pnpm --filter @outstaff/protocol run docs:protocol`. Do not edit by hand. -->",
    "",
    `**Proposed** ([decision 0016](/decisions/0016-event-pipeline/)). Link version: **${LINK_VERSION}**. The office link connects an office to a monitoring or management service, for example a dashboard. The office connects out to the service; the service never connects to an office. The service keeps no office data: it asks the office over this connection, so an office that is offline shows nothing. The messages are defined as schemas in the \`@outstaff/protocol\` package.`,
    "",
    "## Connecting",
    "",
    `- The office opens a WebSocket to \`link.url\` from the team file, with the headers \`Authorization: Bearer <OUTSTAFF_LINK_TOKEN>\` and \`Outstaff-Link-Version: ${LINK_VERSION}\`. A service that does not accept the token refuses the upgrade (HTTP 401 or 403).`,
    '- Messages are JSON text frames: `{ "type": "request", "payload": { ... } }`. A frame that does not parse is ignored; a request that does not, when its `id` can be read, gets an `invalid` error.',
    "- The service sends `welcome` first. With another `version` the office closes the connection with code 4426. After the welcome the office sends `people`, then notifications as things change, and answers requests.",
    "- Either side sends `ping` when it has been quiet; the other answers `pong`. The office closes a connection that stays silent for three of its ping intervals.",
    "- When the connection drops or is refused, the office tries again with a backoff that doubles up to a cap. The link never holds up the office.",
    "",
    "## Requests",
    "",
    "The service sends `request` with an `id`, a `method` and its `params`; the office answers one `response` with that `id` and either `result` or `error`. Requests are answered in any order. A request the office cannot answer in time gets `timeout`. Times are ISO-8601 UTC; cursors are times, never ids.",
    "",
    `Error codes: ${LINK_ERROR_CODES.map((c) => `\`${c}\``).join(", ")}.`,
    "",
    "## Methods",
    "",
    ...(Object.keys(LINK_METHOD_META) as LinkMethod[]).flatMap(methodSection),
    "## Messages",
    "",
    ...(Object.keys(LINK_MESSAGE_META) as LinkMessageType[]).flatMap(messageSection),
  ];

  return lines.join("\n").replace(/\n+$/, "\n");
}
