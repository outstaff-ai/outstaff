import { z } from "zod";
import { MESSAGE_META } from "./meta.js";
import { ERROR_CODES, PROTOCOL_VERSION } from "./constants.js";
import { messageSchema } from "./schemas/message.js";
import type { MessageType } from "./types.js";

interface JsonSchema {
  type?: string | string[];
  enum?: unknown[];
  const?: unknown;
  properties?: Record<string, JsonSchema>;
  required?: string[];
  items?: JsonSchema;
  description?: string;
  anyOf?: JsonSchema[];
}

function typeOf(s: JsonSchema): string {
  if (s.enum) {
    return s.enum.map((v) => `\`${String(v)}\``).join(" or ");
  }

  if (s.anyOf) {
    return s.anyOf.map(typeOf).join(" or ");
  }

  if (s.type === "array" && s.items) {
    return `list of ${typeOf(s.items)}`;
  }

  if (s.type === "object" && s.properties) {
    return `object (${Object.keys(s.properties).join(", ")})`;
  }

  return Array.isArray(s.type) ? s.type.join(" or ") : (s.type ?? "any");
}

const escape = (s: string) => s.replaceAll("|", "\\|").replaceAll("\n", " ");

function payloadOf(type: MessageType): JsonSchema {
  const option = messageSchema.options.find((o) => o.shape.type.value === type);
  if (!option) {
    throw new Error(`No schema for ${type}`);
  }

  return z.toJSONSchema(option.shape.payload, { io: "input" }) as JsonSchema;
}

/** A table padded the way the formatter writes it, so the committed page stays formatted. */
function table(rows: string[][]): string[] {
  const widths = (rows[0] ?? []).map((_, i) =>
    Math.max(3, ...rows.map((r) => (r[i] ?? "").length)),
  );

  const line = (r: string[]) => `| ${r.map((c, i) => c.padEnd(widths[i] ?? 0)).join(" | ")} |`;
  const [head, ...body] = rows;
  return [
    line(head ?? []),
    `| ${widths.map((w) => "-".repeat(w)).join(" | ")} |`,
    ...body.map(line),
  ];
}

/** One row per field; fields of nested objects get dotted names, and `[]` marks list items. */
function fieldRows(s: JsonSchema, prefix: string): string[][] {
  return Object.entries(s.properties ?? {}).flatMap(([name, field]) => {
    const required = s.required?.includes(name) ? "yes" : "no";
    const path = `${prefix}${name}`;
    const item = field.type === "array" ? field.items : undefined;
    const nested = field.properties ? field : item?.properties ? item : undefined;
    const type = nested ? (item ? "list of objects" : "object") : typeOf(field);
    const row = [`\`${path}\``, escape(type), required, escape(field.description ?? "")];
    return nested ? [row, ...fieldRows(nested, `${path}${item ? "[]" : ""}.`)] : [row];
  });
}

function section(type: MessageType): string[] {
  const meta = MESSAGE_META[type];
  const payload = payloadOf(type);
  const lines = [`### \`${type}\``, "", meta.summary, ""];
  lines.push(
    `Sent by: ${meta.from === "both" ? "either side" : meta.from}.` +
      (meta.replies.length
        ? ` Answered by: ${meta.replies.map((r) => `\`${r}\``).join(", ")}.`
        : ""),
    "",
  );

  const rows = fieldRows(payload, "");
  if (rows.length) {
    lines.push(...table([["Field", "Type", "Required", "Description"], ...rows]));
  } else {
    lines.push("No payload fields.");
  }

  lines.push("");
  return lines;
}

/** The reference page for the agent protocol; the docs build commits the output of this function. */
export function renderProtocolReference(): string {
  const types = Object.keys(MESSAGE_META) as MessageType[];
  const lines = [
    "---",
    "title: Agent protocol",
    "description: The messages agents and the office exchange over the agent connection.",
    "---",
    "",
    "<!-- Generated by `pnpm --filter @outstaff/protocol run docs:protocol`. Do not edit by hand. -->",
    "",
    `Protocol version: **${PROTOCOL_VERSION}**. Agents open the connection to the office; the office never connects to an agent. The messages are defined once, as schemas in the \`@outstaff/protocol\` package, which both sides use.`,
    "",
    "## Framing",
    "",
    "Messages are JSON text frames over a WebSocket. Every message has this shape:",
    "",
    "```json",
    '{ "id": "m1", "replyTo": "m0", "type": "heartbeat", "payload": {} }',
    "```",
    "",
    "- `id` is unique per sender. `replyTo` is set on a response and holds the `id` of the request.",
    "- A request gets exactly one response: the result message listed for it, `ack`, or `error`.",
    "- The first message from the agent must be `hello`. Anything else gets an `unauthenticated` error and the connection closes.",
    "- A message that is not valid JSON, has an unknown `type`, or has a payload that does not match gets an `error` back. The connection stays open.",
    "- Frames are limited to 1 MiB.",
    "",
    "## Connection life cycle",
    "",
    "1. The agent connects and sends `hello` with its handle, token and protocol version.",
    "2. The office answers `welcome`, or `error` and closes the connection (`auth_failed`, `version_mismatch`). The close codes are 4401 and 4426.",
    "3. The office offers the next work item, or offers again the items that were not accepted before. The agent sends `accept` (or `decline`).",
    "4. While working the agent sends `heartbeat` at least every `heartbeatMs`, `progress` and `journal` as it goes, and finally `handback` or `fail`. The office then offers the next item.",
    "5. A person has one connection. A new connection with valid credentials replaces the old one, which closes with code 4409.",
    "6. After a disconnect the agent reconnects with backoff and sends `hello` again. `welcome.resume` lists accepted items still unfinished, and unaccepted offers are delivered again.",
    "",
    "Delivery is at least once and idempotent by work item id: an offer may arrive twice, and `accept`, `handback` and the other item messages may be repeated safely.",
    "",
    "## Error codes",
    "",
    ERROR_CODES.map((c) => `\`${c}\``).join(", ") + ".",
    "",
    "## Messages",
    "",
    ...types.flatMap(section),
  ];

  return lines.join("\n").replace(/\n+$/, "\n");
}
