import type { SecretSection, SecretSpec, TeamConfig } from "@outstaff/core";
import type { Scope } from "./types.js";

const sentence = (s: string) => (/[.!?]$/.test(s) ? s : `${s}.`);

function describe(s: SecretSpec, handle: string): string[] {
  const lines = [sentence(s.description), `Where: ${sentence(s.where)}`];
  const flags = [s.optional ? "Optional." : "Required.", ...(s.derivable ? ["Derivable."] : [])];
  lines.push(
    s.derivable
      ? `${flags.join(" ")} Leave it empty and run \`ost setup ${handle} --derive\`.`
      : flags.join(" "),
  );

  return lines.map((l) => `# ${l}`);
}

export function renderEnvExample(
  team: TeamConfig,
  scope: Scope,
  handle: string,
  list: SecretSection[],
  secretsDir: string,
): string {
  const who =
    scope === "office" ? `the ${team.team.name} office` : `${handle} on ${team.team.name}`;

  const lines = [
    `# Outstaff credentials for ${who}. Generated by \`ost setup ${handle}\`; never put real values in this file.`,
    "#",
    "# Preferred: one file per key in a secrets directory, named after the key, holding only the value.",
    "# The container reads them from /run/secrets/outstaff or from OUTSTAFF_SECRETS_DIR.",
    "#",
    `#   ${secretsDir}/`,
    ...list.flatMap((s) => s.specs.map((k) => `#     ${k.key}`)),
    "#",
    "# Fallback for platforms that can only inject environment variables: copy this file to `.env`,",
    "# fill it in and keep it out of git. Anything in the environment is visible to the agent's shell.",
  ];

  for (const section of list) {
    lines.push("", `# --- ${section.title} ---`);
    for (const spec of section.specs) {
      lines.push("", ...describe(spec, handle), `${spec.key}=`);
    }
  }

  return `${lines.join("\n")}\n`;
}
