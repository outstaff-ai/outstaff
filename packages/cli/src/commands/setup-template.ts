import {
  networkGrants,
  type AdapterDefinition,
  type SecretSpec,
  type TeamConfig,
} from "@outstaff/core";

export type Scope = "person" | "office";

// Definitions with different option types live in one list.
// oxlint-disable-next-line no-explicit-any
export type AnyDef = AdapterDefinition<any, any, any>;

export interface Section {
  title: string;
  specs: SecretSpec[];
}

export const tokenKey = (handle: string) =>
  `OUTSTAFF_AGENT_TOKEN_${handle.toUpperCase().replaceAll("-", "_")}`;

/** Keys the framework itself reads, ahead of the adapters' own. */
export function coreSpecs(
  team: TeamConfig,
  scope: Scope,
  person?: TeamConfig["people"][number],
): SecretSpec[] {
  if (scope === "person") {
    const tokens = person
      ? networkGrants(team, person).http.flatMap((g) =>
          g.token
            ? [
                {
                  key: g.token,
                  description: `Bearer token for the "${g.name}" service (${g.url}), sent by \`ost http\`; the agent never sees it`,
                  where: "The service's own settings, for example a long-lived access token",
                },
              ]
            : [],
        )
      : [];

    return [
      {
        key: "OUTSTAFF_AGENT_TOKEN",
        description:
          "This person's token for the office, the same value the office holds as OUTSTAFF_AGENT_TOKEN_<HANDLE>. Choose a long random value",
        where: "Generate it yourself, for example with `openssl rand -hex 32`",
      },
      ...new Map(tokens.map((t) => [t.key, t])).values(),
    ];
  }

  return team.people.map((p) => ({
    key: tokenKey(p.handle),
    description: `Token that lets ${p.name} (${p.handle}) connect to the office; give the same value to that agent as OUTSTAFF_AGENT_TOKEN`,
    where: "Generate it yourself, for example with `openssl rand -hex 32`",
  }));
}

/** One section per adapter, the same key listed once even when several adapters (tracker and knowledge) share it. */
export function sections(
  team: TeamConfig,
  defs: AnyDef[],
  scope: Scope,
  person?: TeamConfig["people"][number],
): Section[] {
  const seen = new Set<string>();
  const out: Section[] = [{ title: "outstaff", specs: coreSpecs(team, scope, person) }];
  for (const s of out[0]!.specs) {
    seen.add(s.key);
  }

  for (const def of defs) {
    const specs = def
      .secrets(scope, person ? { team, person } : undefined)
      .filter((s) => !seen.has(s.key));

    for (const s of specs) {
      seen.add(s.key);
    }

    if (specs.length > 0) {
      out.push({ title: `${def.name} (${def.port})`, specs });
    }
  }

  return out;
}

const sentence = (s: string) => (/[.!?]$/.test(s) ? s : `${s}.`);

function describe(s: SecretSpec, handle: string): string[] {
  const lines = [sentence(s.description), `Where: ${sentence(s.where)}`];
  const flags = [s.optional ? "Optional." : "Required.", ...(s.derivable ? ["Derivable."] : [])];
  lines.push(
    s.derivable
      ? `${flags.join(" ")} Leave it empty and run \`ost setup ${handle} --derive\`.`
      : flags.join(" "),
  );

  return lines.map((l) => `# ${l}`);
}

export function renderEnvExample(
  team: TeamConfig,
  scope: Scope,
  handle: string,
  list: Section[],
  secretsDir: string,
): string {
  const who =
    scope === "office" ? `the ${team.team.name} office` : `${handle} on ${team.team.name}`;

  const lines = [
    `# Outstaff credentials for ${who}. Generated by \`ost setup ${handle}\`; never put real values in this file.`,
    "#",
    "# Preferred: one file per key in a secrets directory, named after the key, holding only the value.",
    "# The container reads them from /run/secrets/outstaff or from OUTSTAFF_SECRETS_DIR.",
    "#",
    `#   ${secretsDir}/`,
    ...list.flatMap((s) => s.specs.map((k) => `#     ${k.key}`)),
    "#",
    "# Fallback for platforms that can only inject environment variables: copy this file to `.env`,",
    "# fill it in and keep it out of git. Anything in the environment is visible to the agent's shell.",
  ];

  for (const section of list) {
    lines.push("", `# --- ${section.title} ---`);
    for (const spec of section.specs) {
      lines.push("", ...describe(spec, handle), `${spec.key}=`);
    }
  }

  return `${lines.join("\n")}\n`;
}
