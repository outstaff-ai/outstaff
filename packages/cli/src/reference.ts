import { commands } from "./commands/index.js";
import { GLOBAL_OPTIONS, type CommandDef, type OptionDef } from "./define.js";

const path = (c: CommandDef) => (c.group ? `${c.group} ${c.name}` : c.name);

const options = (list: OptionDef[]) =>
  [
    "| Option | Description |",
    "| --- | --- |",
    ...list.map((o) => `| \`${o.flags}\` | ${o.description} |`),
  ].join("\n");

/** Markdown for the CLI reference page, generated from the command definitions. */
export function renderCliReference(): string {
  const out: string[] = [
    "---",
    "title: CLI reference",
    "description: Commands and options of the ost command line.",
    "---",
    "",
    "<!-- Generated by `pnpm --filter outstaff run docs:cli`. Do not edit by hand. -->",
    "",
    "The CLI is installed as `outstaff` with the alias `ost`.",
    "",
    "```",
    "ost [global options] <command> [options]",
    "```",
    "",
    "## Global options",
    "",
    options(GLOBAL_OPTIONS),
  ];

  for (const c of commands) {
    out.push(
      "",
      `## ost ${path(c)}`,
      "",
      c.summary,
      "",
      c.description,
      "",
      "```",
      `ost ${path(c)}${c.args ? ` ${c.args}` : ""}${c.options.length ? " [options]" : ""}`,
      "```",
    );

    if (c.options.length) {
      out.push("", options(c.options));
    }

    out.push("", "Exit codes:", "", ...c.exitCodes.map((e) => `- ${e}`));
    out.push("", "Examples:", "", "```sh", ...c.examples, "```");
  }

  return `${out.join("\n")}\n`;
}
