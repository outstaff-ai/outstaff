import { subjectOf } from "#/pipeline/describe.js";
import type { ReplayResult, ReplayRow } from "./replay.types.js";

const cell = (lines: string[]) =>
  (lines.length > 0 ? lines.join("<br>") : "-").replaceAll("|", "\\|");

function eventCell(row: ReplayRow): string {
  const e = row.event;
  const by = e.actor.kind === "automation" ? "" : ` by ${e.actor.id}`;
  const cause = e.data["cause"] as { pr: { number: number } } | undefined;
  const after = cause ? ` after #${cause.pr.number}` : "";
  return `${row.derived ? "derived " : ""}\`${e.type}\` ${subjectOf(e)}${by}${after}`;
}

const HEADER = [
  "# Replay: acme events through today's engine and the event pipeline",
  "",
  "Generated by `packages/office/src/pipeline/replay/__tests__/replay.test.ts`; `UPDATE_GOLDEN=1` rewrites it. Do not edit by hand.",
  "",
  "How to read it:",
  "",
  "- **Today** is the engine's workflow rules (the acme team's kanban preset, with `policies.merge.on_approval` on), plus the checks the engine makes before applying an effect that need no store: untrusted events and pending review comments are ignored, and a schedule for the agent who caused the event is skipped. It leaves out what the engine does outside its rules (moving a ticket to active when work starts, assigning an attached ticket back, retrying blocked items on a human's signal, joining or attaching to a queued item), so a move missing from the pipeline column is not by itself a regression.",
  "- **Pipeline** is the default policy set. Tracker changes are made by the office for the agent named, with a comment saying so; a drop says why nothing happens.",
  "- Two sides are the same when they wake the same people for the same kinds and make the same tracker changes, whoever makes them. Today's `conflict` kind is compared as the pipeline's `rebase`.",
  "- A merge re-checks the repository's other open pull requests. Today raises `pr.conflicted` only for a pull request that turned conflicting; the pipeline raises `pr.conflicted`, `pr.behind_base` or `pr.base_merged` for every pull request the merge changed something under.",
  "- Every difference has a note: an intended fix or a regression.",
];

/** The replay as a Markdown report, for a person to read and for the golden file. */
export function renderReplayReport(result: ReplayResult): string {
  const rows = result.scenarios.flatMap((s) => s.rows);
  const differ = rows.filter((r) => !r.same);
  const count = (prefix: string) => differ.filter((r) => r.note?.startsWith(prefix)).length;
  const out = [
    ...HEADER,
    "",
    `**${rows.length} events** (${rows.filter((r) => r.derived).length} derived from merges): ${rows.length - differ.length} decided the same, ${differ.length} differently (${count("intended fix")} intended fixes, ${count("regression")} regressions).`,
  ];

  let n = 0;
  for (const s of result.scenarios) {
    out.push(
      "",
      `## ${s.title}`,
      "",
      "| # | Event | Today | Pipeline | Note |",
      "| - | - | - | - | - |",
    );

    for (const r of s.rows) {
      n++;
      out.push(
        `| ${n} | ${eventCell(r)} | ${cell(r.today)} | ${cell(r.pipeline)} | ${r.same ? "same" : cell([r.note ?? ""])} |`,
      );
    }
  }

  const folded = result.coalesced.filter((c) => c.events.length > 1);
  const wakes = result.coalesced.reduce((sum, c) => sum + c.events.length, 0);
  out.push(
    "",
    "## Coalescing",
    "",
    `The pipeline's ${wakes} wakes become ${result.coalesced.length} runs when wakes for the same person and subject within the window are folded together.`,
    "",
  );

  for (const c of folded) {
    out.push(
      `- ${c.person}, ${c.kind} on ${c.subject}: ${c.events.length} events (${c.events.join(", ")})`,
    );
  }

  return `${out.join("\n")}\n`;
}
