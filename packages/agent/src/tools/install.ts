import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { silentLogger, type EffectiveTool, type Logger } from "@outstaff/core";
import { runMise } from "./mise.js";
import type { MiseRunner, ToolStatus } from "./types.js";

export interface InstallToolsOptions {
  tools: EffectiveTool[];
  home: string;
  env?: NodeJS.ProcessEnv;
  mise?: MiseRunner;
  log?: Logger;
}

export interface InstallToolsResult {
  statuses: ToolStatus[];

  /** Where mise puts its shims; put it on PATH for the runtime's child processes. */
  shimsDir: string;
}

interface State {
  /** Hash of mise.toml. */
  config: string;

  /** Hash of mise.toml and the lockfile after the last successful install. */
  applied: string;
}

const sha = (text: string) => createHash("sha256").update(text).digest("hex");
const read = (file: string) => (existsSync(file) ? readFileSync(file, "utf8") : "");

const quote = (s: string) => JSON.stringify(s);

/** The mise key of a tool: its explicit source, else its name (mise's registry). */
export const miseKey = (t: EffectiveTool) => t.source ?? t.name;

export function renderMiseToml(tools: EffectiveTool[]): string {
  return [
    "# Generated by the outstaff agent from the toolsets and team.yaml. Edits are overwritten at start.",
    "[settings]",
    "lockfile = true",
    "",
    "[tools]",
    ...tools.map((t) => `${quote(miseKey(t))} = ${quote(t.version)}`),
    "",
  ].join("\n");
}

/** The reason mise gave, without its progress bars, version footer and hints. */
const lastLine = (r: { stderr: string; stdout: string }) => {
  const lines = `${r.stderr}\n${r.stdout}`
    .split("\n")
    .map((l) => l.replace(/^mise (ERROR|WARN)\s+/, "").trim())
    .filter((l) => l && !/█|^Version:|^Run with|^hint:|^deprecated/.test(l));

  const failed = lines.filter((l) => /failed|error|not found|not installed/i.test(l));
  return (failed.length ? failed : lines).slice(0, 2).join(" ") || "no output";
};

/**
 * Installs the effective tools with mise into the agent's home. The work is skipped when neither the tool list
 * nor the lockfile changed since the last successful install. When it fails, the tools that did not install are
 * named and the rest stay usable; nothing is recorded, so the next start tries again.
 */
export async function installTools(opts: InstallToolsOptions): Promise<InstallToolsResult> {
  const log = opts.log ?? silentLogger;
  const mise = opts.mise ?? runMise;
  const base = opts.env ?? process.env;
  const dataDir = base["MISE_DATA_DIR"] ?? join(opts.home, ".local/share/mise");
  const shimsDir = join(dataDir, "shims");
  const dir = join(opts.home, ".config/outstaff/tools");
  const tomlFile = join(dir, "mise.toml");
  const lockFile = join(dir, "mise.lock");
  const stateFile = join(dir, "state.json");

  const status = (state: ToolStatus["state"], error?: string): ToolStatus[] =>
    opts.tools.map((t) => ({
      name: t.name,
      version: t.version,
      state,
      ...(error ? { error } : {}),
    }));

  if (opts.tools.length === 0) {
    return { statuses: [], shimsDir };
  }

  mkdirSync(dir, { recursive: true });
  const toml = renderMiseToml(opts.tools);
  writeFileSync(tomlFile, toml);
  const config = sha(toml);

  let state: State | undefined;
  try {
    state = JSON.parse(read(stateFile)) as State;
  } catch {
    state = undefined;
  }

  if (state?.applied === sha(toml + read(lockFile))) {
    log.debug("tools unchanged, skipping install");
    return { statuses: status("cached"), shimsDir };
  }

  const env = {
    ...base,
    MISE_DATA_DIR: dataDir,
    MISE_YES: "1",
    MISE_TRUSTED_CONFIG_PATHS: dir,
  };

  const run = (args: string[]) => mise(args, { cwd: dir, env });

  // A lock that belongs to this exact tool list is enforced; any other change refreshes it first.
  const locked = existsSync(lockFile) && state?.config === config;
  const steps: string[][] = locked ? [["install", "--locked"]] : [["lock"], ["install"]];
  let failure: string | undefined;
  for (const step of steps) {
    const r = await run(step);
    if (r.code !== 0) {
      failure = `mise ${step.join(" ")} failed: ${lastLine(r)}`;
      break;
    }
  }

  if (!failure) {
    writeFileSync(stateFile, JSON.stringify({ config, applied: sha(toml + read(lockFile)) }));
    log.info("tools installed", { tools: opts.tools.map((t) => `${t.name}@${t.version}`) });
    return { statuses: status("installed"), shimsDir };
  }

  // One tool failing fails the batch; install them one by one to say which.
  const statuses: ToolStatus[] = [];
  for (const t of opts.tools) {
    const r = await run(["install", `${miseKey(t)}@${t.version}`]);
    statuses.push({
      name: t.name,
      version: t.version,
      state: r.code === 0 ? "installed" : "unavailable",
      ...(r.code === 0
        ? {}
        : { error: `${t.name}@${t.version} could not be installed: ${lastLine(r)}` }),
    });
  }

  if (statuses.every((s) => s.state === "installed")) {
    // The batch failed on the lockfile or settings only; the tools themselves are in place.
    log.warn("tools installed one by one", { reason: failure });
    return { statuses, shimsDir };
  }

  for (const s of statuses) {
    if (s.error) {
      log.error("tool unavailable", { tool: s.name, version: s.version, reason: s.error });
    }
  }

  return { statuses, shimsDir };
}
