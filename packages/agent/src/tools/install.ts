import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { silentLogger, type EffectiveTool, type Logger } from "@outstaff/core";
import { dataDirOf, lastLine, miseKey, runMise } from "./mise.js";
import { verifyTools } from "./verify.js";
import type { InstallToolsOptions, InstallToolsResult, MiseResult, ToolStatus } from "./types.js";

interface State {
  /** Hash of mise.toml. */
  config: string;

  /** Hash of mise.toml and the lockfile after the last successful install. */
  applied: string;
}

const sha = (text: string) => createHash("sha256").update(text).digest("hex");
const read = (file: string) => (existsSync(file) ? readFileSync(file, "utf8") : "");

// JSON string escapes are valid TOML basic-string escapes, except that TOML also forbids a raw DEL.
const quote = (s: string) => JSON.stringify(s).replaceAll("\u007f", "\\u007f");
const tomlKey = (k: string) => (/^[A-Za-z0-9_-]+$/.test(k) ? k : quote(k));

type TomlTable = { [key: string]: string | TomlTable };

const inlineTable = (table: TomlTable): string =>
  `{ ${Object.entries(table)
    .map(([k, v]) => `${tomlKey(k)} = ${typeof v === "string" ? quote(v) : inlineTable(v)}`)
    .join(", ")} }`;

/** What a tool is set to in mise.toml: its version, or an inline table when it has options. */
const miseValue = (t: EffectiveTool) =>
  t.options && Object.keys(t.options).length > 0
    ? inlineTable({ version: t.version, ...t.options })
    : quote(t.version);

export function renderMiseToml(tools: EffectiveTool[]): string {
  return [
    "# Generated by the outstaff agent from the toolsets and team.yaml. Edits are overwritten at start.",
    "[settings]",
    "lockfile = true",
    "",
    "[tools]",
    ...tools.map((t) => `${quote(miseKey(t))} = ${miseValue(t)}`),
    "",
  ].join("\n");
}

/**
 * The global mise config: every declared tool at its version, so a shim resolves in any directory. A repo's own
 * mise config or `.tool-versions` still wins inside that repo.
 */
export function renderGlobalMiseToml(tools: EffectiveTool[]): string {
  return [
    "# Generated by the outstaff agent from the toolsets and team.yaml. Edits are overwritten at start.",
    "[tools]",
    ...tools.map((t) => `${quote(miseKey(t))} = ${miseValue(t)}`),
    "",
  ].join("\n");
}

/** Where mise reads the global config: `MISE_GLOBAL_CONFIG_FILE` when set, else `~/.config/mise/config.toml`. */
export const globalConfigFile = (home: string, env: NodeJS.ProcessEnv = process.env) =>
  env["MISE_GLOBAL_CONFIG_FILE"] || join(home, ".config/mise/config.toml");

function writeGlobalConfig(tools: EffectiveTool[], home: string, env: NodeJS.ProcessEnv) {
  const file = globalConfigFile(home, env);
  const text = renderGlobalMiseToml(tools);
  if (read(file) !== text) {
    mkdirSync(dirname(file), { recursive: true });
    writeFileSync(file, text);
  }
}

/**
 * Installs the effective tools with mise into the agent's home. The work is skipped when neither the tool list
 * nor the lockfile changed since the last successful install. When it fails, the tools that did not install are
 * named and the rest stay usable; nothing is recorded, so the next start tries again.
 */
export async function installTools(opts: InstallToolsOptions): Promise<InstallToolsResult> {
  const result = await installAll(opts);
  if (opts.tools.length === 0 || result.statuses.some((s) => s.state === "unavailable")) {
    return result;
  }

  // Install is not enough: every tool must also resolve outside the generated project config.
  const base = opts.env ?? process.env;
  writeGlobalConfig(opts.tools, opts.home, base);
  const failed = await verifyTools({
    tools: opts.tools,
    home: opts.home,
    env: base,
    ...(opts.mise ? { mise: opts.mise } : {}),
  });

  if (failed.length === 0) {
    return result;
  }

  const log = opts.log ?? silentLogger;
  for (const s of failed) {
    log.error("tool unavailable", { tool: s.name, version: s.version, reason: s.error });
  }

  return {
    ...result,
    statuses: result.statuses.map((s) => failed.find((f) => f.name === s.name) ?? s),
  };
}

/** Where the agent keeps its mise project, lock and install state, and where mise keeps its data. */
function toolPaths(home: string, env: NodeJS.ProcessEnv) {
  const dataDir = dataDirOf(home, env);
  const dir = join(home, ".config/outstaff/tools");

  return {
    dataDir,
    shimsDir: join(dataDir, "shims"),
    dir,
    tomlFile: join(dir, "mise.toml"),
    lockFile: join(dir, "mise.lock"),
    stateFile: join(dir, "state.json"),
  };
}

type ToolPaths = ReturnType<typeof toolPaths>;

/** The state of the last successful install; none when it is missing or unreadable. */
function readState(file: string): State | undefined {
  try {
    return JSON.parse(read(file)) as State;
  } catch {
    return undefined;
  }
}

const allAs = (tools: EffectiveTool[], state: ToolStatus["state"]): ToolStatus[] =>
  tools.map((t) => ({ name: t.name, version: t.version, state }));

/** A lock that belongs to this exact tool list is enforced; any other change refreshes it first. */
const batchSteps = (paths: ToolPaths, state: State | undefined, config: string): string[][] =>
  existsSync(paths.lockFile) && state?.config === config
    ? [["install", "--locked"]]
    : [["lock"], ["install"]];

type RunMise = (args: string[]) => Promise<MiseResult>;

/** Runs the steps in order; the first that fails stops the batch, and its reason is returned. */
async function runSteps(run: RunMise, steps: string[][]): Promise<string | undefined> {
  for (const step of steps) {
    const r = await run(step);
    if (r.code !== 0) {
      return `mise ${step.join(" ")} failed: ${lastLine(r)}`;
    }
  }

  return undefined;
}

async function installOne(run: RunMise, t: EffectiveTool): Promise<ToolStatus> {
  const r = await run(["install", `${miseKey(t)}@${t.version}`]);
  if (r.code === 0) {
    return { name: t.name, version: t.version, state: "installed" };
  }

  return {
    name: t.name,
    version: t.version,
    state: "unavailable",
    error: `${t.name}@${t.version} could not be installed: ${lastLine(r)}`,
  };
}

/** One tool failing fails the batch; install them one by one to say which. */
async function installOneByOne(
  run: RunMise,
  tools: EffectiveTool[],
  failure: string,
  log: Logger,
): Promise<ToolStatus[]> {
  const statuses: ToolStatus[] = [];
  for (const t of tools) {
    statuses.push(await installOne(run, t));
  }

  if (statuses.every((s) => s.state === "installed")) {
    // The batch failed on the lockfile or settings only; the tools themselves are in place.
    log.warn("tools installed one by one", { reason: failure });
    return statuses;
  }

  for (const s of statuses.filter((x) => x.error)) {
    log.error("tool unavailable", { tool: s.name, version: s.version, reason: s.error });
  }

  return statuses;
}

async function installAll(opts: InstallToolsOptions): Promise<InstallToolsResult> {
  const log = opts.log ?? silentLogger;
  const base = opts.env ?? process.env;
  const paths = toolPaths(opts.home, base);
  const shimsDir = paths.shimsDir;
  if (opts.tools.length === 0) {
    return { statuses: [], shimsDir };
  }

  mkdirSync(paths.dir, { recursive: true });
  const toml = renderMiseToml(opts.tools);
  writeFileSync(paths.tomlFile, toml);
  const config = sha(toml);
  const state = readState(paths.stateFile);
  if (state?.applied === sha(toml + read(paths.lockFile))) {
    log.debug("tools unchanged, skipping install");
    return { statuses: allAs(opts.tools, "cached"), shimsDir };
  }

  const env = {
    ...base,
    MISE_DATA_DIR: paths.dataDir,
    MISE_YES: "1",
    MISE_TRUSTED_CONFIG_PATHS: paths.dir,
  };

  const mise = opts.mise ?? runMise;
  const run = (args: string[]) => mise(args, { cwd: paths.dir, env });
  const failure = await runSteps(run, batchSteps(paths, state, config));
  if (failure) {
    return { statuses: await installOneByOne(run, opts.tools, failure, log), shimsDir };
  }

  writeFileSync(
    paths.stateFile,
    JSON.stringify({ config, applied: sha(toml + read(paths.lockFile)) }),
  );

  log.info("tools installed", { tools: opts.tools.map((t) => `${t.name}@${t.version}`) });

  return { statuses: allAs(opts.tools, "installed"), shimsDir };
}
